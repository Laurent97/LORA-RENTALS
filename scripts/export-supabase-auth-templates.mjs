// Exports the LORA OTP designs as Supabase Auth email templates.
//   npx tsx scripts/export-supabase-auth-templates.mjs
// → supabase/auth-templates/{confirmation,magic_link,recovery,email_change,reauthentication}.html
//
// Paste each file into Supabase Dashboard → Authentication → Email Templates
// (or reference them from supabase/config.toml for local dev). Supabase renders
// Go templates, so the code placeholder is {{ .Token }} and the user's name comes
// from signUp metadata as {{ .Data.name }}.
import { mkdirSync, writeFileSync } from "node:fs";
import { renderEmail } from "../lib/postmark/render.ts";

const out = "supabase/auth-templates";
mkdirSync(out, { recursive: true });

// Supabase template → our slug + the Go variables it should carry.
// Sentinel strings survive HTML-escaping and are swapped for Go tags afterwards.
const NAME = "__GO_NAME__";
const CODE = "__GO_TOKEN__";
const MAP = {
  confirmation: { slug: "auth-otp-signup", subject: "Your LORA Signup Code: {{ .Token }}" },
  magic_link: { slug: "auth-otp-login", subject: "Your LORA Login Code: {{ .Token }}" },
  recovery: { slug: "auth-otp-password-reset", subject: "Reset Your LORA Password — Code: {{ .Token }}" },
  email_change: { slug: "auth-otp-email-change-new", subject: "Verify New Email — Code: {{ .Token }}" },
  reauthentication: { slug: "auth-otp-login", subject: "Confirm It's You — Code: {{ .Token }}" },
};

const goName = `{{ if .Data.name }}{{ .Data.name }}{{ else }}there{{ end }}`;

for (const [file, { slug, subject }] of Object.entries(MAP)) {
  const data = {
    first_name: NAME,
    code: CODE,
    new_device: false,
    new_email: "{{ .NewEmail }}",
    old_email: "{{ .Email }}",
  };
  let { html } = renderEmail(slug, data, "en", { userId: "" });
  html = html
    .replaceAll(NAME, goName)
    .replaceAll(CODE, "{{ .Token }}")
    // aria-label spelled the sentinel out digit-by-digit; collapse it
    .replace(/aria-label="Verification code [^"]*"/, 'aria-label="Verification code"');
  writeFileSync(`${out}/${file}.html`, html);
  writeFileSync(`${out}/${file}.subject.txt`, subject);
  console.log(`wrote ${out}/${file}.html`);
}

writeFileSync(
  `${out}/README.md`,
  `# Supabase Auth email templates

Generated by \`scripts/export-supabase-auth-templates.mjs\` from the LORA Postmark designs — do not edit by hand.

| File | Supabase template | Subject |
|---|---|---|
${Object.entries(MAP).map(([f, m]) => `| \`${f}.html\` | ${f.replace("_", " ")} | \`${m.subject}\` |`).join("\n")}

## Install

1. Supabase Dashboard → **Authentication → Email Templates** → pick the template → paste the HTML and subject.
2. **Authentication → Providers → Email**: enable *Confirm email*; set OTP length **8**, expiry **600s**.
3. **Project Settings → Auth → SMTP**: use Postmark — host \`smtp.postmarkapp.com\`, port 587,
   user + password = your Postmark **Server API token**, sender \`noreply@lorarentals.org\`.
   Add the header \`X-PM-Message-Stream: outbound\` if you use a non-default stream.

The app verifies codes with \`supabase.auth.verifyOtp({ email, token, type })\` on \`/verify\`.
`
);
